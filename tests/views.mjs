// Headless flows for Split View, Preview, Mini Window and media (round 2a). Captures land in SWYR_TEST_OUT.
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { launch, sleep } from './harness.mjs'

const out = process.env.SWYR_TEST_OUT || fs.mkdtempSync(path.join(os.tmpdir(), 'swyr-views-'))
fs.mkdirSync(out, { recursive: true })
const frame = (name) => path.join(out, name + '.png')

const t = await launch({ log: process.env.SWYR_TEST_LOG === '1' })
const step = (name) => console.log('step', name)
const split = (s) => s.items.find((i) => i.kind === 'split')
const tabJs = (itemId, code) =>
  t.app.evaluate(({ webContents }, [url, js]) => {
    const wc = webContents.getAllWebContents().find((w) => w.getURL().startsWith(url))
    return wc ? wc.executeJavaScript(js, true) : 'no-contents'
  }, [itemId, code])
const key = (urlPrefix, keyCode, modifiers) =>
  t.app.evaluate(({ webContents }, [u, k, m]) => {
    const wc = webContents.getAllWebContents().find((w) => w.getURL().startsWith(u))
    wc.sendInputEvent({ type: 'keyDown', keyCode: k, modifiers: m })
    wc.sendInputEvent({ type: 'keyUp', keyCode: k, modifiers: m })
  }, [urlPrefix, keyCode, modifiers])

try {
  let s = await t.waitFor((s) => s.windows?.length === 1, 'initial state')
  await t.dispatch('space.edit', { theme: { appearance: 'light' } })

  step('split.add without an item adds a new tab pane')
  await t.dispatch('tab.new', { url: 'https://example.com' })
  s = await t.waitFor((s) => s.items.some((i) => /Example/.test(i.title)), 'tab 1')
  const first = s.items[0]
  await t.dispatch('split.add')
  s = await t.waitFor((s) => split(s)?.panes.itemIds.length === 2, 'split of 2')
  assert.equal(s.windows[0].activeItemId, split(s).id)
  assert.equal(s.windows[0].focusedPane, 1)
  assert.equal(split(s).section, 'today')
  assert.equal(s.windows[0].paneRects.length, 2)
  assert.equal(s.windows[0].dividers.length, 1)
  const [r0, r1] = s.windows[0].paneRects
  assert.equal(r1.x - (r0.x + r0.width), 6, '6 px gap')

  step('navigate the focused pane, focus by shortcut, swap, ratios')
  await t.dispatch('tab.navigate', { input: 'example.org' })
  s = await t.waitFor((s) => s.items.some((i) => /example\.org/.test(i.url) && i.parentId === split(s).id), 'pane navigated')
  await key('swyr://shell', '1', ['control', 'shift'])
  s = await t.waitFor((s) => s.windows[0].focusedPane === 0, 'ctrl+shift+1')
  assert.match(split(s).url, /example\.com/, 'split mirrors the focused pane url')
  await key('swyr://shell', ']', ['control', 'shift'])
  s = await t.waitFor((s) => s.windows[0].focusedPane === 1, 'ctrl+shift+]')
  await t.dispatch('split.swap', { from: 1, to: 2 })
  s = await t.state()
  assert.equal(split(s).panes.itemIds[1], first.id)
  assert.equal(s.windows[0].focusedPane, 0)
  const ratios = await t.dispatch('split.setRatios', { ratios: [0.95, 0.05] })
  assert.ok(Math.abs(ratios[0] - 0.8) < 1e-6 && Math.abs(ratios[1] - 0.2) < 1e-6, 'clamped to 80/20: ' + ratios)
  const dragged = await t.dispatch('split.setRatios', { divider: 0, pos: 600 })
  assert.ok(dragged[0] > 0.2 && dragged[0] < 0.5, 'divider drag ' + dragged)

  step('ctrl+shift+= adds a third pane, four is the max')
  await key('swyr://shell', '=', ['control', 'shift'])
  s = await t.waitFor((s) => split(s)?.panes.itemIds.length === 3, 'ctrl+shift+=')
  assert.ok(await t.dispatch('split.add'))
  assert.equal(await t.dispatch('split.add'), false, 'max 4 panes')
  s = await t.state()
  assert.equal(split(s).panes.itemIds.length, 4)
  await t.dispatch('split.setLayout', { layout: 'vertical' })
  await sleep(600)
  await t.capture(frame('v01-split4-vertical'))

  step('cmd+w closes the focused pane only; closing to one pane dissolves the split')
  await t.dispatch('split.setLayout', { layout: 'horizontal' })
  await t.dispatch('tab.close')
  s = await t.waitFor((s) => split(s)?.panes.itemIds.length === 3, 'cmd+w closed a pane')
  assert.equal(s.archive.at(-1).reason, 'closed')
  await t.dispatch('split.remove')
  await t.dispatch('split.remove', { keep: true })
  s = await t.waitFor((s) => !split(s), 'dissolved')
  assert.ok(s.items.every((i) => !i.parentId), 'no orphans')
  assert.equal(s.windows[0].paneRects.length, 1)

  step('drag-to-split drop and pane activation')
  const ids = s.items.filter((i) => i.section === 'today').map((i) => i.id)
  await t.dispatch('tab.activate', { id: ids[0] })
  await t.waitIdle()
  await t.dispatch('split.dropZones', { show: true })
  s = await t.state()
  assert.equal(s.windows[0].overlay?.kind, 'splitDrop')
  await sleep(400)
  await t.capture(frame('v02-drop-zones'))
  await t.dispatch('split.drop', { itemId: ids[1], edge: 'left' })
  s = await t.waitFor((s) => split(s)?.panes.itemIds[0] === ids[1], 'dropped on the left')
  assert.equal(s.windows[0].overlay, null)
  await t.dispatch('tab.new', { url: 'swyr://newtab' })
  await t.dispatch('tab.activate', { id: ids[0] })
  s = await t.state()
  assert.equal(s.windows[0].activeItemId, split(s).id, 'activating a pane activates its split')
  assert.equal(s.windows[0].focusedPane, 1)

  step('pinning the split pins its panes; closing the split row archives everything')
  await t.dispatch('tab.pin')
  s = await t.waitFor((s) => split(s)?.section === 'pinned' && s.items.filter((i) => i.parentId === split(s).id).every((i) => i.section === 'pinned'), 'pinned split')
  await t.dispatch('tab.unpin')
  s = await t.waitFor((s) => split(s)?.section === 'today', 'unpinned split')
  const sp = split(s)
  await t.dispatch('tab.close', { id: sp.id })
  s = await t.waitFor((s) => !split(s) && !s.items.some((i) => i.parentId === sp.id), 'split archived')
  s = await t.waitFor((s) => sp.panes.itemIds.every((id) => !s.windows[0].loaded.includes(id)), 'pane views released')

  step('a cross-site link in a pinned tab opens Preview; Escape closes it')
  await t.dispatch('tab.new', { url: 'https://example.com/pinned' })
  s = await t.waitFor((s) => s.items.some((i) => /example\.com\/pinned/.test(i.url) && /Example/.test(i.title)), 'pinned page')
  const pin = s.items.find((i) => /example\.com\/pinned/.test(i.url))
  await t.dispatch('tab.pin', { id: pin.id })
  await tabJs('https://example.com/pinned', `location.href = 'https://example.org/from-pinned'; 1`)
  s = await t.waitFor((s) => s.windows[0].preview?.url.includes('example.org/from-pinned'), 'preview from link')
  assert.equal(s.windows[0].preview.fromItemId, pin.id)
  assert.match(s.items.find((i) => i.id === pin.id).url, /example\.com\/pinned/, 'pinned tab stays on its page')
  await key('swyr://overlay', 'Escape', [])
  s = await t.waitFor((s) => !s.windows[0].preview && !s.windows[0].overlay, 'escape closed preview')
  await tabJs('https://example.com/pinned', `window.open('https://example.net/popup'); 1`)
  s = await t.waitFor((s) => s.windows[0].preview?.url.includes('example.net/popup'), 'preview from window.open')
  await t.dispatch('commandbar.open', { mode: 'new' })
  s = await t.state()
  assert.equal(s.windows[0].preview, null, 'another overlay replaces the preview')
  await t.dispatch('commandbar.close')

  step('preview expand keeps the live page as a Today tab')
  await t.dispatch('preview.open', { url: 'https://example.org/keep', fromItemId: pin.id })
  await t.waitFor((s) => s.windows[0].preview?.title === 'Example Domain', 'preview loaded')
  const n = (await t.state()).items.length
  const newId = await t.dispatch('preview.expand')
  s = await t.state()
  assert.equal(s.items.length, n + 1)
  assert.equal(s.windows[0].activeItemId, newId)
  assert.ok(s.windows[0].loaded.includes(newId))
  assert.equal(s.windows[0].tabs[newId].loading, false, 'adopted view, not reloaded')

  step('mini window: create, capture, chrome IPC, open in a chosen space')
  await t.dispatch('space.new', { name: 'Work' })
  s = await t.state()
  const work = s.spaces.find((x) => x.name === 'Work')
  await t.dispatch('space.switch', { index: 0 })
  const miniId = await t.dispatch('mini.new', { url: 'https://example.com/mini' })
  s = await t.waitFor((s) => s.windows.find((w) => w.kind === 'mini')?.url.includes('example.com/mini'), 'mini loaded')
  const mini = s.windows.find((w) => w.kind === 'mini')
  assert.equal(mini.id, miniId)
  assert.equal(mini.bounds.width, 560)
  assert.equal(mini.bounds.height, 720)
  assert.equal(s.windows[0].kind, 'main')
  await sleep(1200)
  assert.ok(await t.app.evaluate((_e, f) => globalThis.__swyr.captureMini(f), frame('v03-mini')))
  // the chrome's own channel only runs mini.* commands
  const denied = await t.app.evaluate(async ({ BrowserWindow }, id) => {
    const wc = BrowserWindow.fromId(id).webContents
    return wc.executeJavaScript(`window.swyrMini.invoke('tab.new', {}).then(() => 'ran', () => 'denied')`)
  }, miniId)
  assert.equal(denied, 'denied')
  await key('https://example.com/mini', 'O', ['meta'])
  s = await t.waitFor((s) => !s.windows.some((w) => w.kind === 'mini'), 'cmd+o moved the mini page')
  const moved = s.items.find((i) => /example\.com\/mini/.test(i.url))
  assert.equal(moved.section, 'today')
  assert.equal(s.windows[0].activeItemId, moved.id)
  await t.dispatch('mini.new', { url: 'https://example.org/second' })
  await t.waitFor((s) => s.windows.some((w) => w.kind === 'mini'), 'second mini')
  await t.dispatch('mini.openInMain', { spaceId: work.id })
  s = await t.waitFor((s) => s.items.some((i) => /example\.org\/second/.test(i.url) && i.spaceId === work.id), 'moved into Work')
  assert.equal(s.windows[0].activeSpaceId, work.id)

  step('media: playing tab shows in the sidebar from another tab; toggle pauses it')
  await t.dispatch('tab.new', { url: 'https://example.com/media' })
  await t.waitFor((s) => s.items.some((i) => /example\.com\/media/.test(i.url) && /Example/.test(i.title)), 'media page')
  const played = await tabJs(
    'https://example.com/media',
    `(() => {
      const rate = 8000, n = rate * 3, buf = new ArrayBuffer(44 + n * 2), v = new DataView(buf)
      const w = (o, s) => [...s].forEach((c, i) => v.setUint8(o + i, c.charCodeAt(0)))
      w(0, 'RIFF'); v.setUint32(4, 36 + n * 2, true); w(8, 'WAVEfmt '); v.setUint32(16, 16, true); v.setUint16(20, 1, true)
      v.setUint16(22, 1, true); v.setUint32(24, rate, true); v.setUint32(28, rate * 2, true); v.setUint16(32, 2, true)
      v.setUint16(34, 16, true); w(36, 'data'); v.setUint32(40, n * 2, true)
      for (let i = 0; i < n; i++) v.setInt16(44 + i * 2, Math.sin(i / 4) * 300, true)
      const a = document.createElement('audio')
      a.src = URL.createObjectURL(new Blob([buf], { type: 'audio/wav' }))
      a.loop = true
      document.body.appendChild(a)
      return a.play().then(() => 'playing', (e) => String(e))
    })()`
  )
  assert.equal(played, 'playing')
  s = await t.waitFor((s) => s.windows[0].media?.playing, 'media runtime')
  const mediaId = s.windows[0].media.itemId
  await t.dispatch('settings.set', { pipAuto: true })
  await t.dispatch('tab.activate', { id: s.items.find((i) => /example\.org\/second/.test(i.url)).id })
  s = await t.state()
  assert.notEqual(s.windows[0].activeItemId, mediaId)
  assert.ok(s.windows[0].loaded.includes(mediaId), 'playing tab stays loaded')
  await sleep(700)
  await t.capture(frame('v04-media-bar'))
  assert.equal(await t.dispatch('media.toggle'), 'paused')
  s = await t.waitFor((s) => s.windows[0].media && !s.windows[0].media.playing, 'paused')
  await t.dispatch('media.close')
  s = await t.waitFor((s) => !s.windows[0].media, 'media cleared')

  console.log(`views: passed, frames in ${out}`)
} finally {
  await t.close()
}
