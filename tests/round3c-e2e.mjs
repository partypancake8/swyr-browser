// Round 3c flows: onboarding, Chrome bookmarks, the shortcut table, error page, new tab page, window bounds,
// private windows. Captures land in SWYR_TEST_OUT.
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { launch, repo, sleep } from './harness.mjs'

const out = process.env.SWYR_TEST_OUT || fs.mkdtempSync(path.join(os.tmpdir(), 'swyr-3c-'))
fs.mkdirSync(out, { recursive: true })
const frame = (name) => path.join(out, name + '.png')
const step = (name) => console.log('step', name)
const activeUrl = (s, win = s.windows[0]) => s.items.find((i) => i.id === win.activeItemId)?.url || ''
const evalTab = (t, js) => t.app.evaluate((_e, code) => globalThis.__swyr.evalInActiveTab(code), js)
const dispatchIn = (t, id, command, payload) => t.app.evaluate((_e, a) => globalThis.__swyr.dispatchIn(a.id, a.command, a.payload), { id, command, payload })

let t = await launch({ onboarding: true, log: process.env.SWYR_TEST_LOG === '1' })
const userData = t.userData
try {
  step('first run opens onboarding')
  let s = await t.waitFor((s) => s.windows?.length === 1 && /^swyr:\/\/onboarding/.test(activeUrl(s)), 'onboarding tab')
  assert.notEqual(s.settings.onboarded, true)
  await t.dispatch('space.edit', { theme: { appearance: 'light' } })
  for (let i = 0; i < 5; i++) {
    await t.dispatch('tab.navigate', { url: `swyr://onboarding?step=${i}` })
    await t.waitIdle()
    await sleep(700)
    await t.capture(frame(`onboarding-${i + 1}`))
  }
  await t.dispatch('space.edit', { theme: { appearance: 'dark' } })
  await t.dispatch('tab.navigate', { url: 'swyr://onboarding?step=2' })
  await t.waitIdle()
  await sleep(700)
  await t.capture(frame('onboarding-3-dark'))
  await t.dispatch('space.edit', { theme: { appearance: 'light' } })

  step('import Chrome bookmarks into a pinned folder')
  const imp = await t.dispatch('import.chrome', { path: path.join(repo, 'tests/fixtures/chrome/Bookmarks') })
  assert.equal(imp.bookmarks, 3, JSON.stringify(imp))
  s = await t.state()
  const folder = s.items.find((i) => i.id === imp.folderId)
  assert.equal(folder.kind, 'folder')
  assert.equal(folder.section, 'pinned')
  const inside = s.items.filter((i) => i.parentId === folder.id)
  assert.ok(inside.some((i) => i.url === 'https://example.com/'))
  assert.ok(inside.some((i) => i.kind === 'folder' && i.title === 'Reading'))
  assert.ok(inside.some((i) => i.kind === 'folder' && i.title === 'Other Bookmarks'))

  step('finish onboarding')
  await t.dispatch('onboarding.complete', { themeColors: ['#BFE3DA', '#9CC9E8'], adblock: false, archiveAfter: '7d' })
  s = await t.waitFor((s) => s.settings.onboarded === true && /^swyr:\/\/newtab/.test(activeUrl(s)), 'newtab after onboarding')
  assert.deepEqual(s.spaces[0].theme.colors, ['#bfe3da', '#9cc9e8'])
  assert.equal(s.settings.adblock, false)
  assert.equal(s.settings.archiveAfter, '7d')

  step('shortcut table')
  const table = await t.dispatch('shortcuts.list')
  assert.ok(table.length >= 80, 'bindings: ' + table.length)
  for (const b of table) assert.ok(b.id && b.command && b.accelerator && b.default, JSON.stringify(b))
  const cmdT = table.find((b) => b.id === 'tab.new')
  assert.equal(cmdT.accelerator, 'Cmd+T')
  assert.equal(table.find((b) => b.command === 'page.readerMode').accelerator, 'Cmd+Alt+R')
  assert.equal(table.find((b) => b.command === 'mini.openInMain').scope, 'mini')
  let r = await t.dispatch('shortcuts.set', { id: 'tab.reopen', accelerator: 'Cmd+D' })
  assert.equal(r.ok, false)
  assert.equal(r.conflict.id, 'tab.togglePin')
  r = await t.dispatch('shortcuts.set', { id: 'tab.reopen', accelerator: 'Y' })
  assert.equal(r.ok, false)
  r = await t.dispatch('shortcuts.set', { id: 'tab.reopen', accelerator: 'Cmd+Shift+Y' })
  assert.equal(r.ok, true)
  s = await t.state()
  assert.equal(s.settings.shortcuts['tab.reopen'], 'Cmd+Shift+Y')
  assert.equal((await t.dispatch('shortcuts.list')).find((b) => b.id === 'tab.reopen').overridden, true)
  // a mini-scope key may repeat a main-scope key, but not another mini binding
  assert.equal((await t.dispatch('shortcuts.set', { id: 'mini.close', accelerator: 'Cmd+O' })).ok, false)
  await t.dispatch('shortcuts.reset', { id: 'tab.reopen' })
  s = await t.state()
  assert.equal(s.settings.shortcuts['tab.reopen'], undefined)

  step('settings shortcuts pane')
  await t.dispatch('shortcuts.open')
  s = await t.waitFor((s) => /^swyr:\/\/settings#shortcuts/.test(activeUrl(s)), 'settings shortcuts')
  await t.waitIdle()
  await sleep(900)
  await t.capture(frame('settings-shortcuts'))

  step('about panel')
  const about = await t.dispatch('app.about')
  assert.equal(about.applicationName, 'swyr')
  assert.match(about.copyright, /Sawyer Smith/)
  assert.match(about.credits, /MIT/)
  assert.ok(about.iconPath && fs.existsSync(about.iconPath), 'icon ' + about.iconPath)

  step('pages, copy as markdown, a raw shortcut key')
  await t.dispatch('tab.new', { url: 'https://example.com' })
  s = await t.waitFor((s) => /Example Domain/.test(s.items.find((i) => i.id === s.windows[0].activeItemId)?.title || ''), 'example loaded')
  assert.equal(await t.dispatch('page.copyUrlMarkdown'), '[Example Domain](https://example.com/)')
  await t.dispatch('tab.favorite')
  await t.dispatch('tab.navigate', { url: 'https://example.org' })
  await t.waitFor((s) => /example\.org/.test(activeUrl(s)), 'example.org')
  await t.waitIdle()
  // Cmd+Shift+[ (a before-input-event binding) goes back
  await t.app.evaluate(({ webContents }) => {
    const all = webContents.getAllWebContents().filter((wc) => /example\.org/.test(wc.getURL()))
    for (const wc of all) {
      wc.sendInputEvent({ type: 'keyDown', keyCode: '[', modifiers: ['meta', 'shift'] })
      wc.sendInputEvent({ type: 'keyUp', keyCode: '[', modifiers: ['meta', 'shift'] })
    }
  })
  await t.waitFor((s) => /example\.com/.test(activeUrl(s)), 'back via Cmd+Shift+[', 10000)

  step('error page keeps the failed URL and retries')
  await t.dispatch('tab.new', { url: 'http://localhost:1/' })
  await sleep(2500)
  const text = await evalTab(t, 'document.body.innerText')
  assert.match(text, /can.t|could not|unable|refused|failed/i)
  assert.match(text, /Retry/)
  assert.match(text, /Copy URL/)
  s = await t.state()
  const bad = s.items.find((i) => i.id === s.windows[0].activeItemId)
  assert.equal(bad.url, 'http://localhost:1/')
  await t.capture(frame('error-light'))

  step('new tab page with favorites and archive')
  for (const url of ['https://example.net', 'https://example.org/?a=1']) {
    await t.dispatch('tab.new', { url })
    await t.waitIdle()
    await t.dispatch('tab.close')
  }
  await t.dispatch('tab.new')
  await t.waitFor((s) => /^swyr:\/\/newtab/.test(activeUrl(s)), 'newtab')
  await t.waitIdle()
  await sleep(900)
  const ntText = await evalTab(t, 'document.body.innerText')
  assert.match(ntText, /Recently archived/i)
  assert.match(ntText, /Library/)
  await t.capture(frame('newtab-light'))
  await t.dispatch('space.edit', { theme: { appearance: 'dark' } })
  await sleep(700)
  await t.capture(frame('newtab-dark'))
  await t.dispatch('space.edit', { theme: { appearance: 'light' } })

  step('private window')
  await t.dispatch('window.newIncognito')
  s = await t.waitFor((s) => s.windows.some((w) => w.incognito === true), 'private window')
  const inc = s.windows.find((w) => w.incognito)
  assert.equal(s.windows.find((w) => !w.incognito && w.kind === 'main').incognito, false)
  await dispatchIn(t, inc.id, 'tab.new', { url: 'https://example.com' })
  await t.waitFor((s) => /example\.com/.test(activeUrl(s, s.windows.find((w) => w.id === inc.id))), 'private tab')
  const part = await t.app.evaluate((_e, id) => globalThis.__swyr.partitionOf(id), inc.id)
  assert.match(part, /^incognito-\d+$/)
  await sleep(800)
  await dispatchIn(t, inc.id, 'page.runJs', { js: "document.cookie = 'swyrprivate=1; max-age=3600'; localStorage.setItem('k', 'v'); document.cookie" })
  const before = await t.app.evaluate(({ session }, p) => session.fromPartition(p).cookies.get({}).then((c) => c.length), part)
  assert.ok(before > 0, 'private cookie set')
  const onDisk = JSON.parse(fs.readFileSync(path.join(userData, 'state.json'), 'utf8'))
  assert.ok(!onDisk.profiles.some((p) => p.incognito), 'private profile never written')
  await dispatchIn(t, inc.id, 'window.close')
  s = await t.waitFor((s) => !s.windows.some((w) => w.incognito) && !s.profiles.some((p) => p.incognito), 'private window gone')
  await sleep(800)
  const after = await t.app.evaluate(({ session }, p) => session.fromPartition(p).cookies.get({}).then((c) => c.length), part)
  assert.equal(after, 0, 'private cookies cleared on close')

  step('window bounds persist across launches')
  const set = await t.dispatch('window.setBounds', { x: 90, y: 70, width: 1100, height: 760 })
  assert.equal(set.width, 1100)
  await sleep(600)
  await t.close()
  t = await launch({ userData, onboarding: true })
  s = await t.waitFor((s) => s.windows?.length === 1, 'relaunch')
  assert.equal(s.windows[0].bounds.width, 1100)
  assert.equal(s.windows[0].bounds.height, 760)
  assert.equal(s.windows[0].bounds.x, 90)
  assert.ok(!/^swyr:\/\/onboarding/.test(activeUrl(s)), 'no onboarding once finished')
  console.log('round 3c e2e passed; frames in', out)
} finally {
  await t.close()
}
