export type SpaceIconName = (typeof SPACE_ICONS)[number][0]

export const DEFAULT_SPACE_ICON: SpaceIconName = 'home'

const NAMES: ReadonlySet<string> = new Set(SPACE_ICONS.map((i) => i[0]))

export function isSpaceIcon(name: unknown): name is SpaceIconName {
  return typeof name === 'string' && NAMES.has(name)
}

export function searchSpaceIcons(query: string): SpaceIconName[] {
  const q = query.trim().toLowerCase()
  if (!q) return SPACE_ICONS.map((i) => i[0])
  return SPACE_ICONS.filter(([name, words]) => name.includes(q) || words.split(' ').some((w) => w.startsWith(q))).map((i) => i[0])
}
