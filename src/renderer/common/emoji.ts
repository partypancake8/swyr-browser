export function searchEmoji(query: string): string[] {
  const q = query.trim().toLowerCase()
  if (!q) return EMOJI.map((e) => e[0])
  return EMOJI.filter(([e, words]) => e === q || words.split(' ').some((w) => w.startsWith(q)) || words.includes(q)).map((e) => e[0])
}
