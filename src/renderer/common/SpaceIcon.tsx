/** the Lucide component for a space icon name; unknown names fall back to the default icon */
export function iconFor(name: string | undefined): LucideIcon {
  return ICONS[isSpaceIcon(name) ? name : DEFAULT_SPACE_ICON]
}

export function SpaceIcon({ name, ...props }: { name: string | undefined } & LucideProps): React.JSX.Element {
  const Icon = iconFor(name)
  return <Icon aria-hidden {...props} />
}
