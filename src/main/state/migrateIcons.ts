/** map an old emoji (or an icon name) to a Lucide icon name */
export function iconFromEmoji(value: unknown): SpaceIconName {
  if (typeof value !== 'string') return DEFAULT_SPACE_ICON
  const v = value.trim()
  if (isSpaceIcon(v)) return v
  return EMOJI_TO_ICON[v.replace(/\uFE0F/g, '')] ?? DEFAULT_SPACE_ICON
}

/** replace a space's emoji field with an icon field, in place; true when something changed */
export function migrateSpaceIcon(space: Record<string, unknown>): boolean {
  const had = 'emoji' in space
  const icon = isSpaceIcon(space.icon) ? space.icon : iconFromEmoji(space.emoji)
  const changed = had || space.icon !== icon
  space.icon = icon
  delete space.emoji
  return changed
}
